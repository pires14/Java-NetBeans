public class Aula04_SwitchCase {
    public static void main(String[] args) {
        String dia = "claro";
        switch(dia){
            case "claro" : System.out.println("Você vai trabalhar");
            break;
            case "noite": System.out.println("Você vai dormir!");
            break;
            default: System.out.println("Você vai estudar!");
            break;
        
        
        }
                
    }
}
